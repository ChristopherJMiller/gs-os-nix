#!/usr/bin/env bash
# Milestone M2: an Apple IIgs, with the card in a slot, computes a store path
# byte-identical to upstream nix.
#
# Runs MAME headlessly under debugger control (mame/debug/m2.txt), reads the 32
# characters the demo left at $0300, and compares them against the golden vector.
#
# Requires an `apple2gs` ROM, which is NOT redistributable. Point MAME at yours
# with ROMPATH, e.g.
#     ROMPATH=~/mame/roms just m2
# Without it this exits 77 (skipped) rather than failing, so CI stays honest
# about the difference between "broken" and "cannot be tested here".
set -uo pipefail

MAME=${MAME:-./result/bin/mame}
ROMPATH=${ROMPATH:-$HOME/mame/roms}
SLOT=${SLOT:-4}
BIN=target/build/storepath_demo_headless.bin
SCRIPT=mame/debug/m2.txt
WORK=${WORK:-target/build/m2}

SKIP=77

die()  { echo "M2 FAIL: $*" >&2; exit 1; }
skip() { echo "M2 SKIP: $*" >&2; exit $SKIP; }

[ -x "$MAME" ] || skip "no MAME at $MAME (build it with: just mame-build)"
[ -f "$BIN" ]  || die  "missing $BIN (build it with: just asm-headless)"

# The expected answer comes from tests/vectors/l1.txt, which was generated by the
# real nix binary -- not from anything in this repo's own logic.
EXPECT=$(awk '/nix-on-an-apple-iigs/ {print $3}' tests/vectors/l1.txt)
[ -n "$EXPECT" ] || die "no expected value for nix-on-an-apple-iigs in tests/vectors/l1.txt"

if ! "$MAME" -rompath "$ROMPATH" apple2gs -listslots >/dev/null 2>&1; then
    skip "MAME cannot enumerate apple2gs (ROMs missing from $ROMPATH?)"
fi
if ! "$MAME" -rompath "$ROMPATH" -verifyroms apple2gs >/dev/null 2>&1; then
    skip "apple2gs ROMs not found or incomplete in $ROMPATH"
fi

mkdir -p "$WORK"
rm -f "$WORK/m2-result.txt"

echo "=== M2: apple2gs with a2nix in slot $SLOT ==="
( cd "$WORK" && ln -sfn ../../../"$BIN" . 2>/dev/null || true )

# -video none / -sound none keep it headless; -seconds_to_run bounds it so a
# hang becomes a failure rather than an indefinite wait.
"$MAME" \
    -rompath "$ROMPATH" \
    apple2gs \
    -sl"$SLOT" a2nix \
    -video none -sound none -nothrottle \
    -seconds_to_run 10 \
    -debug -debugscript "$SCRIPT" \
    > "$WORK/mame.log" 2>&1
rc=$?

RESULT_FILE=m2-result.txt
[ -f "$RESULT_FILE" ] || RESULT_FILE="$WORK/m2-result.txt"

if [ ! -f "$RESULT_FILE" ]; then
    echo "--- mame.log (tail) ---" >&2
    tail -30 "$WORK/mame.log" >&2
    die "MAME produced no result dump (exit $rc)"
fi

# The dump is `address: xx xx ... chars`; take the ASCII column MAME appends.
GOT=$(awk -F'  +' '{print $NF}' "$RESULT_FILE" | tr -d '\n' | head -c 32)
STATUS=$(grep -oE "M2 status byte: [0-9A-Fa-f]{2}" "$WORK/mame.log" | tail -1 | awk '{print $NF}')

echo "  status byte : ${STATUS:-<none>}"
echo "  expected    : $EXPECT"
echo "  got         : $GOT"

[ "${STATUS:-00}" = "01" ] || die "demo did not report success (status ${STATUS:-<none>})"
[ "$GOT" = "$EXPECT" ] || die "store path mismatch"

echo "M2 PASS: the Apple IIgs computed a store path identical to upstream nix"
