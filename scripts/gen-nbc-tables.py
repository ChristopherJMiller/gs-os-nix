#!/usr/bin/env python3
"""target/vm/c/nbc_tables.h: what the on-target compiler (compile.c) takes
from nbc, generated from nbc's own sources so the two cannot drift
(docs/COMPILER.md "Stage 3"):

  PRIMOP_TABLE       opcodes.rs PRIMOPS: each name, then its id and arity bytes
  GLOBAL_TABLE       opcodes.rs GLOBALS
  NIX_BUILTIN_TABLE  opcodes.rs NIX_BUILTINS
  VALUE_TABLE        opcodes.rs BUILTIN_VALUES: each name, then its value: S
                     and a string, I and a decimal, or L (the empty list)
  DERIVATION_NIX     derivation.nix, the file nbc embeds

A table's entry is a length byte, the bytes and a NUL -- a lookup steps
over an entry without scanning it -- and it ends with a zero length. As
string literals they stay with compile.c's code; a static array would be
bank 0's.

usage: gen-nbc-tables.py [--check | --selftest]
  --check     the header is up to date
  --selftest  a drift planted in each source is caught by --check (D14)
"""
import re
import sys

RS, NIX, OUT = "tools/nbc/src/opcodes.rs", "tools/nbc/src/derivation.nix", "target/vm/c/nbc_tables.h"


def block(src, name):
    m = re.search(r"pub const " + name + r": &\[[^=]*= &\[(.*?)\n\];", src, re.S)
    if not m:
        sys.exit(f"gen-nbc-tables: no {name} in {RS}")
    return "\n".join(l.split("//")[0] for l in m.group(1).splitlines())


def esc(b):
    """bytes as C literal text: a byte outside printable ASCII as a 3-digit
    octal escape, which no following character can extend"""
    return "".join("\\\\" if c == 0x5C else '\\"' if c == 0x22 else chr(c) if 0x20 <= c < 0x7F else f"\\{c:03o}"
                   for c in b)


def literal(items, width=96):
    """Each item its length, its bytes and a NUL, then a zero length, as
    concatenated literals; an item (bytes) or a pair (name, extra bytes)"""
    lines, cur = [], ""
    for it in items:
        name, extra = it if isinstance(it, tuple) else (it, b"")
        piece = esc(bytes([len(name)]) + name) + "\\000" + esc(extra)
        if cur and len(cur) + len(piece) > width:
            lines.append(cur)
            cur = ""
        cur += piece
    lines.append(cur + "\\000")
    return " \\\n".join(f'    "{l}"' for l in lines)


def render(rs=None, text=None):
    rs = open(RS).read() if rs is None else rs
    prims = re.findall(r'\("([^"]+)", 0x([0-9A-Fa-f]{2}), (\d)\)', block(rs, "PRIMOPS"))
    globs = re.findall(r'"([^"]+)"', block(rs, "GLOBALS"))
    names = re.findall(r'"([^"]+)"', block(rs, "NIX_BUILTINS"))
    vals = []
    for n, kind, arg in re.findall(r'\("([^"]+)", BuiltinValue::(\w+)(?:\(([^)]*)\))?\)', block(rs, "BUILTIN_VALUES")):
        tag = {"Str": "S" + arg.strip('"'), "Int": "I" + arg, "EmptyList": "L"}[kind]
        vals += [n.encode(), tag.encode()]
    if len(prims) < 90 or len(globs) < 10 or len(names) < 100 or len(vals) != 8:
        sys.exit(f"gen-nbc-tables: {RS}'s tables did not parse")
    text = open(NIX, "rb").read() if text is None else text
    lines = text.split(b"\n")
    body = [esc(l) + "\\n" for l in lines[:-1]] + ([esc(lines[-1])] if lines[-1] else [])
    return ("/* nbc_tables.h -- generated by scripts/gen-nbc-tables.py from nbc's\n"
            " * opcodes.rs and derivation.nix; do not edit. checks.nbc-opcodes holds it to\n"
            " * them. What compile.c takes from nbc, as string literals: a static array\n"
            " * would be bank 0's. An entry: its length, its bytes, NUL; a zero length ends\n"
            " * a table. */\n\n"
            "/* PRIMOPS: a name, then its id and its arity as two bytes */\n"
            "#define PRIMOP_TABLE \\\n" +
            literal([(n.encode(), bytes([int(i, 16), int(a)])) for n, i, a in prims]) + "\n\n"
            "/* GLOBALS: the builtins Nix also exposes unqualified */\n"
            "#define GLOBAL_TABLE \\\n" + literal([g.encode() for g in globs]) + "\n\n"
            "/* NIX_BUILTINS: every name in Nix 2.34.9's builtins */\n"
            "#define NIX_BUILTIN_TABLE \\\n" + literal([n.encode() for n in names]) + "\n\n"
            "/* BUILTIN_VALUES: a name, then its value: S and a string, I and a decimal, or L */\n"
            "#define VALUE_TABLE \\\n" + literal(vals) + "\n\n"
            "/* derivation.nix, the file Nix wraps around derivationStrict */\n"
            f"#define DERIVATION_NIX_LEN {len(text)}U\n"
            "#define DERIVATION_NIX \\\n" + " \\\n".join(f'    "{l}"' for l in body) + "\n")


def selftest():
    """Each drift the header could fall behind, planted in a copy of its source"""
    rs, text, have = open(RS).read(), open(NIX, "rb").read(), open(OUT).read()
    plants = [("a primop's arity", rs.replace('("map", 0x04, 2)', '("map", 0x04, 3)'), text),
              ("a primop's id", rs.replace('("head", 0x01, 1)', '("head", 0x02, 1)'), text),
              ("a global", rs.replace('"placeholder", ', ""), text),
              ("a builtin's name", rs.replace('"warn", ', '"warm", '), text),
              ("a value builtin", rs.replace('BuiltinValue::Str("2.34.9")', 'BuiltinValue::Str("2.34.8")'), text),
              ("derivation.nix's text", rs, text.replace(b"outputsList", b"outputList", 1))]
    ok = True
    for name, r, t in plants:
        caught = (r, t) != (rs, text) and render(r, t) != have
        print(f"  {name:<24} {'caught' if caught else 'SURVIVED'}")
        ok &= caught
    print("NBC TABLES SELFTEST OK" if ok else "NBC TABLES SELFTEST FAILED")
    return 0 if ok else 1


def main():
    if "--selftest" in sys.argv:
        return selftest()
    want = render()
    if "--check" in sys.argv:
        try:
            ok = open(OUT).read() == want
        except FileNotFoundError:
            ok = False
        print("nbc_tables.h: " + ("nbc's tables and derivation.nix, exactly" if ok
                                  else "STALE -- run scripts/gen-nbc-tables.py"))
        return 0 if ok else 1
    open(OUT, "w").write(want)
    return 0


if __name__ == "__main__":
    sys.exit(main())
